package com.societix.audit.internal;

import java.time.OffsetDateTime;
import java.util.UUID;

import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * JPA entity for the append-only {@code audit_records} table (task 11.1; design.md "Data Models" &gt;
 * audit_records, ADR-6; Req 16.1-16.6, 13.5, BR6).
 *
 * <p><strong>Append-only / immutable.</strong> Rows are only ever inserted and read — never updated
 * or deleted. This entity carries no setters and no {@code updated_at}; the application exposes no
 * update/delete path (the {@code AuditService} API has none), and the database enforces the same via
 * the {@code trg_audit_records_immutable} trigger and a least-privilege runtime role (see
 * {@code V3__audit_records.sql}, {@code infra/README.md}). Keeping the entity write-once in Java
 * mirrors that contract: there is nothing here that could issue an {@code UPDATE}.
 *
 * <p><strong>Platform-level nullable tenant.</strong> Unlike tenant-owned entities, {@code societyId}
 * is nullable: it is {@code null} only for platform-level events with no single owning Society
 * (Req 13.5, 16.5). For the same reason this entity is not routed through the tenant-scoping base
 * repository; audit queries apply tenant scope explicitly from {@code TenantContext}.
 *
 * <p><strong>Identifier and timestamp generation.</strong> The {@code id} (UUIDv7) and
 * {@code occurred_at} are produced by the database column defaults ({@code uuid_generate_v7()} and
 * {@code now()}), mapped read-only ({@code insertable=false}) so the database stays authoritative;
 * {@code occurred_at} is read back after insert.
 *
 * <p><strong>JSONB summaries.</strong> {@code beforeSummary}/{@code afterSummary} map the JSONB
 * columns as compact JSON {@code String}s via {@link JdbcTypeCode}({@link SqlTypes#JSON}); callers
 * serialize/inspect the JSON, the audit module just stores the document verbatim.
 */
@Entity
@Table(name = "audit_records")
public class AuditRecord {

    /** Surrogate PK (UUIDv7), generated by the {@code uuid_generate_v7()} column default. */
    @Id
    @GeneratedValue
    @Column(name = "id", nullable = false, updatable = false, insertable = false)
    private UUID id;

    /** Owning Society; {@code null} only for platform-level events (Req 13.5/16.5). Write-once. */
    @Column(name = "society_id", updatable = false)
    private UUID societyId;

    /** Acting user; {@code null} when no user is resolved (e.g. pre-auth system event). Write-once. */
    @Column(name = "actor_user_id", updatable = false)
    private UUID actorUserId;

    /** Short, stable action code (Req 16.1-16.3). Write-once. */
    @Column(name = "action", nullable = false, updatable = false)
    private String action;

    /** Kind of entity acted upon. Write-once. */
    @Column(name = "target_type", nullable = false, updatable = false)
    private String targetType;

    /** Target entity identifier as text; {@code null} when there is no single target. Write-once. */
    @Column(name = "target_id", updatable = false)
    private String targetId;

    /** Compact-JSON summary of state before the change ({@code null} when not applicable). Write-once. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "before_summary", updatable = false)
    private String beforeSummary;

    /** Compact-JSON summary of state after the change ({@code null} when not applicable). Write-once. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "after_summary", updatable = false)
    private String afterSummary;

    /** Event instant (UTC); database-managed via the {@code now()} default, read-only in JPA. */
    @Column(name = "occurred_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime occurredAt;

    /** JPA requires a no-arg constructor. */
    protected AuditRecord() {
        // for JPA
    }

    /**
     * Creates a new, write-once audit record. {@code id} and {@code occurredAt} are assigned by the
     * database on persist.
     *
     * @param societyId     owning Society id, or {@code null} for a platform-level event
     * @param actorUserId   acting user id, or {@code null} when no user is resolved
     * @param action        action code (required, non-blank)
     * @param targetType    target entity type (required, non-blank)
     * @param targetId      target entity identifier as text, or {@code null}
     * @param beforeSummary compact-JSON before-summary, or {@code null}
     * @param afterSummary  compact-JSON after-summary, or {@code null}
     */
    public AuditRecord(
            UUID societyId,
            UUID actorUserId,
            String action,
            String targetType,
            String targetId,
            String beforeSummary,
            String afterSummary) {
        this.societyId = societyId;
        this.actorUserId = actorUserId;
        this.action = action;
        this.targetType = targetType;
        this.targetId = targetId;
        this.beforeSummary = beforeSummary;
        this.afterSummary = afterSummary;
    }

    public UUID getId() {
        return id;
    }

    public UUID getSocietyId() {
        return societyId;
    }

    public UUID getActorUserId() {
        return actorUserId;
    }

    public String getAction() {
        return action;
    }

    public String getTargetType() {
        return targetType;
    }

    public String getTargetId() {
        return targetId;
    }

    public String getBeforeSummary() {
        return beforeSummary;
    }

    public String getAfterSummary() {
        return afterSummary;
    }

    public OffsetDateTime getOccurredAt() {
        return occurredAt;
    }
}
