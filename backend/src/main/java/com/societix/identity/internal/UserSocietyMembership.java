package com.societix.identity.internal;

import com.societix.identity.api.MembershipRole;

import java.time.OffsetDateTime;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * JPA entity for the tenant-owned {@code user_society_memberships} table (task 9.1; design.md
 * "Data Models" &gt; user_society_memberships; Req 3.1, 3.6, A2).
 *
 * <p><strong>Tenant-owned.</strong> A membership scopes a {@link User}'s {@link MembershipRole role}
 * within exactly ONE society (Req 3.6, A2), so it carries a NOT NULL {@code society_id} referencing
 * {@code societies(id)}. It is subject to the tenant-isolation layer (the Hibernate
 * {@code societyFilter} / base-repository predicate and the {@code tenant_isolation} RLS policy).
 *
 * <p><strong>TODO (task 7.3 coordination).</strong> The shared {@code TenantOwnedEntity} base class
 * and the {@code @Filter}/{@code @FilterDef} {@code societyFilter} convention are introduced
 * concurrently in task 7.3. To avoid a file-coordination conflict this entity maps
 * {@code society_id} explicitly as a plain {@code UUID} column for now; once 7.3 lands, migrate this
 * entity to extend the shared tenant-owned base class and apply the {@code @Filter} so tenant
 * scoping is enforced centrally rather than relying only on service-side predicates. Cross-module
 * references to a society use the {@code society_id} UUID here, never a direct import of the tenancy
 * entity (ArchUnit enforces the module boundary).
 *
 * <p><strong>Identifier and timestamps.</strong> The UUIDv7 {@code id}, {@code created_at}, and
 * {@code updated_at} are database-managed (column defaults + {@code set_updated_at()} trigger),
 * mapped read-only so the database stays authoritative.
 */
@Entity
@Table(name = "user_society_memberships")
public class UserSocietyMembership {

    /** Surrogate PK (UUIDv7), generated by the {@code uuid_generate_v7()} column default. */
    @Id
    @GeneratedValue
    @Column(name = "id", nullable = false, updatable = false, insertable = false)
    private UUID id;

    /** FK to the owning {@link User} (by id, not a JPA association). NOT NULL. */
    @Column(name = "user_id", nullable = false)
    private UUID userId;

    /**
     * FK to the one society this membership scopes (by id — cross-module references use the UUID,
     * never a direct import of the tenancy entity). NOT NULL (tenant-owned, Req 1.1).
     */
    @Column(name = "society_id", nullable = false)
    private UUID societyId;

    /**
     * The role held (one of the 11 roles, Req 3.1). Persisted by name as UPPER_SNAKE_CASE text to
     * match the {@code ck_memberships_role} CHECK constraint.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "role", nullable = false)
    private MembershipRole role;

    /**
     * Optional scoping payload for scoped roles (e.g. an assigned flat/building id or a compact JSON
     * document); {@code null} for society-wide roles. Modeled as text so a bare UUID or a small JSON
     * value both fit before the authorization model (task 12.x) finalizes the shape.
     */
    @Column(name = "scope")
    private String scope;

    /**
     * Membership lifecycle. Persisted by name as lowercase text to match the
     * {@code ck_memberships_status} CHECK constraint. Defaults to {@link MembershipStatus#active};
     * ending a membership flips this to {@code ended} (history retained).
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private MembershipStatus status = MembershipStatus.active;

    /** Row-creation instant (UTC). Database-managed via the column default; read-only in JPA. */
    @Column(name = "created_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime createdAt;

    /**
     * Last-modification instant (UTC). Database-managed: column default on insert and the
     * {@code set_updated_at()} trigger on every update. Read-only in JPA.
     */
    @Column(name = "updated_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime updatedAt;

    /** JPA requires a no-arg constructor. */
    protected UserSocietyMembership() {
        // for JPA
    }

    /**
     * Creates a new active membership granting {@code role} to {@code userId} within
     * {@code societyId}, with an optional {@code scope}. The id and timestamps are populated by the
     * database on persist.
     *
     * @param userId    the owning user's id
     * @param societyId the id of the one society this membership scopes
     * @param role      the role held (one of the 11 roles)
     * @param scope     optional scoping payload for scoped roles, or {@code null}
     */
    public UserSocietyMembership(UUID userId, UUID societyId, MembershipRole role, String scope) {
        this.userId = userId;
        this.societyId = societyId;
        this.role = role;
        this.scope = scope;
        this.status = MembershipStatus.active;
    }

    public UUID getId() {
        return id;
    }

    public UUID getUserId() {
        return userId;
    }

    public UUID getSocietyId() {
        return societyId;
    }

    public MembershipRole getRole() {
        return role;
    }

    public String getScope() {
        return scope;
    }

    public void setScope(String scope) {
        this.scope = scope;
    }

    public MembershipStatus getStatus() {
        return status;
    }

    public void setStatus(MembershipStatus status) {
        this.status = status;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public OffsetDateTime getUpdatedAt() {
        return updatedAt;
    }
}
