package com.societix.identity.internal;

import java.time.OffsetDateTime;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * JPA entity for the platform-level {@code users} table — a platform account identity
 * (task 9.1; design.md "Data Models" &gt; users; Req 2.1, 3.1, 18.1, RD8).
 *
 * <p><strong>Platform-level, not tenant-owned.</strong> Like {@link com.societix.tenancy.internal
 * Society}, a {@code User} carries no {@code society_id}: a single account is global to the platform
 * and may hold roles in several societies via {@link UserSocietyMembership}. It is therefore exempt
 * from the central tenant-scoping layer and from the {@code tenant_isolation} RLS policy.
 *
 * <p><strong>Data minimization (RD8 / Req 18.1).</strong> This entity stores only the minimum
 * identity attributes — email, verification flag, password hash, display name, and account-security
 * state. There is deliberately no Aadhaar, PAN, date-of-birth, or ID-document field.
 *
 * <p><strong>Scope of this task.</strong> This models persistence only. Password <em>hashing</em>
 * is task 9.2 and authentication/lockout/verification <em>logic</em> is task 10.x; here
 * {@code passwordHash}, {@code failedAttempts}, {@code lockoutUntil}, and {@code emailVerified} are
 * plain fields. {@code passwordHash} is nullable because an account may exist before a password is
 * set, and it never holds plaintext.
 *
 * <p><strong>Identifier and timestamps.</strong> The UUIDv7 {@code id}, {@code created_at}, and
 * {@code updated_at} are database-managed (column defaults + the {@code set_updated_at()} trigger)
 * and mapped read-only so the database stays authoritative.
 */
@Entity
@Table(name = "users")
public class User {

    /** Surrogate PK (UUIDv7), generated by the {@code uuid_generate_v7()} column default. */
    @Id
    @GeneratedValue
    @Column(name = "id", nullable = false, updatable = false, insertable = false)
    private UUID id;

    /**
     * Login identifier. Case-insensitive uniqueness is enforced in the database by the
     * {@code ux_users_email_lower} functional UNIQUE index on {@code lower(email)}.
     */
    @Column(name = "email", nullable = false)
    private String email;

    /** Whether the email address has been verified (Req 2.14). Verification flow is task 10.3. */
    @Column(name = "email_verified", nullable = false)
    private boolean emailVerified = false;

    /**
     * Salted adaptive one-way password hash (Req 2.4); never plaintext. Nullable until a password
     * is set (hashing is task 9.2).
     */
    @Column(name = "password_hash")
    private String passwordHash;

    /** Display name (RD8). NOT NULL and non-blank (DB CHECK {@code ck_users_full_name_not_blank}). */
    @Column(name = "full_name", nullable = false)
    private String fullName;

    /**
     * Account lifecycle state. Persisted by name as lowercase text to match the
     * {@code ck_users_status} CHECK constraint. Defaults to {@link UserStatus#active}.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private UserStatus status = UserStatus.active;

    /** Consecutive failed-login counter (Req 2.7); non-negative. Lockout logic is task 10.2. */
    @Column(name = "failed_attempts", nullable = false)
    private int failedAttempts = 0;

    /** Instant (UTC) until which login is locked, or {@code null} when not locked (Req 2.8). */
    @Column(name = "lockout_until")
    private OffsetDateTime lockoutUntil;

    /**
     * Start of the current rolling failed-attempt window, or {@code null} when no failures are
     * pending. Failed attempts are counted over a fixed window from this instant (Req 2.7).
     */
    @Column(name = "failure_window_started_at")
    private OffsetDateTime failureWindowStartedAt;

    /**
     * Number of lockout cycles the account has incurred, driving the progressively-longer (but
     * bounded, never permanent) backoff (Req 2.8). Reset to zero on a successful sign-in.
     */
    @Column(name = "lockout_count", nullable = false)
    private int lockoutCount = 0;

    /** Row-creation instant (UTC). Database-managed via the column default; read-only in JPA. */
    @Column(name = "created_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime createdAt;

    /**
     * Last-modification instant (UTC). Database-managed: column default on insert and the
     * {@code set_updated_at()} trigger on every update. Read-only in JPA.
     */
    @Column(name = "updated_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime updatedAt;

    /** JPA requires a no-arg constructor. */
    protected User() {
        // for JPA
    }

    /**
     * Creates a new user with the given email and display name in the default
     * {@link UserStatus#active} state, unverified and with no password set. The id and timestamps
     * are populated by the database on persist.
     *
     * @param email    the login email (non-blank; case-insensitively unique)
     * @param fullName the display name (non-blank)
     */
    public User(String email, String fullName) {
        this.email = email;
        this.fullName = fullName;
        this.emailVerified = false;
        this.status = UserStatus.active;
        this.failedAttempts = 0;
    }

    public UUID getId() {
        return id;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public boolean isEmailVerified() {
        return emailVerified;
    }

    public void setEmailVerified(boolean emailVerified) {
        this.emailVerified = emailVerified;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public void setPasswordHash(String passwordHash) {
        this.passwordHash = passwordHash;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public UserStatus getStatus() {
        return status;
    }

    public void setStatus(UserStatus status) {
        this.status = status;
    }

    public int getFailedAttempts() {
        return failedAttempts;
    }

    public void setFailedAttempts(int failedAttempts) {
        this.failedAttempts = failedAttempts;
    }

    public OffsetDateTime getLockoutUntil() {
        return lockoutUntil;
    }

    public void setLockoutUntil(OffsetDateTime lockoutUntil) {
        this.lockoutUntil = lockoutUntil;
    }

    public OffsetDateTime getFailureWindowStartedAt() {
        return failureWindowStartedAt;
    }

    public void setFailureWindowStartedAt(OffsetDateTime failureWindowStartedAt) {
        this.failureWindowStartedAt = failureWindowStartedAt;
    }

    public int getLockoutCount() {
        return lockoutCount;
    }

    public void setLockoutCount(int lockoutCount) {
        this.lockoutCount = lockoutCount;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public OffsetDateTime getUpdatedAt() {
        return updatedAt;
    }
}
