package com.societix.tenancy.internal;

import java.time.OffsetDateTime;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * JPA entity for the platform-level {@code societies} table — the tenant root of the system
 * (task 7.1; design.md "Data Models" &gt; societies; Req 13.1, 13.3, 1.1, BR9).
 *
 * <p><strong>Platform-level, not tenant-owned.</strong> Unlike every domain entity in later
 * milestones, {@code Society} carries no {@code society_id}: it <em>is</em> the tenant. It is
 * therefore exempt from the central tenant-scoping layer and from the {@code tenant_isolation} RLS
 * policy applied to tenant-owned tables.
 *
 * <p><strong>Scope of this task.</strong> This entity models persistence only — identity, name,
 * {@link SocietyStatus status}, and audit timestamps. Provisioning and suspension behaviour (and
 * any public {@code tenancy.api} service surface) arrive in tasks 32.1/32.2. Accordingly the entity
 * lives in {@code tenancy.internal} and is not exposed across the module boundary.
 *
 * <p><strong>Identifier generation.</strong> The primary key is a UUID whose value is produced by
 * the database {@code uuid_generate_v7()} default (V1 baseline; v7 for index locality). The entity
 * does not generate the id in Java; it lets the column default fill it, so {@code id} is populated
 * on insert and read back. No {@code @Version} optimistic-locking column: the design reserves that
 * for high-contention tables (invoices, bookings, account credits, maintenance requests), and
 * societies are low-write.
 *
 * <p><strong>Timestamps.</strong> {@code created_at} and {@code updated_at} are
 * {@link OffsetDateTime} mapped to {@code TIMESTAMPTZ} (UTC). Both are database-managed: the column
 * defaults set them on insert and the {@code trg_societies_set_updated_at} trigger keeps
 * {@code updated_at} current on every update. They are mapped read-only here
 * ({@code insertable=false, updatable=false}) so the database stays authoritative over clock
 * values rather than the JVM.
 */
@Entity
@Table(name = "societies")
public class Society {

    /**
     * Surrogate primary key (UUIDv7). Generated by the {@code uuid_generate_v7()} column default in
     * the database; mapped read-only so Hibernate relies on the default and reads the value back
     * after insert rather than assigning it in Java.
     */
    @Id
    @GeneratedValue
    @Column(name = "id", nullable = false, updatable = false, insertable = false)
    private UUID id;

    /** Display name of the society; NOT NULL and non-blank (DB CHECK {@code ck_societies_name_not_blank}). */
    @Column(name = "name", nullable = false)
    private String name;

    /**
     * Lifecycle state (active/suspended). Persisted by name as lowercase text to match the
     * {@code ck_societies_status} CHECK constraint. Defaults to {@link SocietyStatus#active}, which
     * also matches the column default for rows created outside JPA.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private SocietyStatus status = SocietyStatus.active;

    /** Row-creation instant (UTC). Database-managed via the column default; read-only in JPA. */
    @Column(name = "created_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime createdAt;

    /**
     * Last-modification instant (UTC). Database-managed: the column default sets it on insert and
     * the {@code set_updated_at()} trigger refreshes it on every update. Read-only in JPA.
     */
    @Column(name = "updated_at", nullable = false, updatable = false, insertable = false)
    private OffsetDateTime updatedAt;

    /** JPA requires a no-arg constructor. */
    protected Society() {
        // for JPA
    }

    /**
     * Creates a new society with the given name in the default {@link SocietyStatus#active} state.
     * The id and timestamps are populated by the database on persist.
     *
     * @param name the society's display name (must be non-blank)
     */
    public Society(String name) {
        this.name = name;
        this.status = SocietyStatus.active;
    }

    public UUID getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public SocietyStatus getStatus() {
        return status;
    }

    public void setStatus(SocietyStatus status) {
        this.status = status;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public OffsetDateTime getUpdatedAt() {
        return updatedAt;
    }
}
